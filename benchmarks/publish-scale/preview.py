#!/usr/bin/env python3
"""ADR-057 condition 6: where a composition preview stops being instant.

The preview reads at most `CompositionPreview.PreviewRecordCeiling` features of
each layer, and that number is 4,000 because 4,000 felt right. The condition
asks for three things the guess cannot answer:

* where a preview stops being instant,
* whether the bound should be the row count or the vertex count,
* and what a composition of a whole database costs, since §5j draws **every**
  layer on every change the screen cannot coalesce.

So this measures a single layer at rising row counts, the same row count at
rising vertex counts, and a composition at rising layer counts -- three curves
rather than one number, because the condition is really asking which variable
the ceiling should be on.

The corpus is generated by `--make`, in its own schema, and dropped by `--drop`.
Nothing here is a fixture anybody else depends on.

Usage:
    python benchmarks/publish-scale/preview.py --make
    python benchmarks/publish-scale/preview.py --url https://127.0.0.1:8451 \\
        --user ci --password '...' --source <data source id>
"""

import argparse
import json
import ssl
import statistics
import subprocess
import sys
import time
import urllib.error
import urllib.request

TIMEOUT = 600
SCHEMA = "zzzprev"

# <b>Rows and vertices, crossed rather than varied one at a time.</b> A ceiling
# on the row count is only right if the cost is in the rows; if it is in the
# vertices then 4,000 simple polygons and 4,000 complex ones are different
# requests wearing one number, which is exactly what the condition suspects.
ROWS = [250, 1000, 2000, 4000, 8000, 16000]
VERTICES = [5, 50, 500]
LAYERS = [1, 5, 10, 25, 50]

# The frame every measurement is taken in, so the numbers are comparable. Web
# Mercator around Ankara, the extent the corpus is generated into.
BBOX = "3650000,4855000,3675000,4880000"
SIZE = "900,620"


def corpus(container):
    """Generates the tables, in one statement per shape.

    <b>Polygons on a grid rather than random.</b> A benchmark whose data moves
    between runs measures the data as well as the server, and the question here
    is about counting, not about spatial distribution.
    """
    sql = [f"create schema if not exists {SCHEMA};"]

    for rows in ROWS:
        for vertices in VERTICES:
            name = f"r{rows}_v{vertices}"

            sql.append(f"""
drop table if exists {SCHEMA}.{name};
create table {SCHEMA}.{name} (objectid serial primary key, geom geometry(Polygon, 3857));
insert into {SCHEMA}.{name} (geom)
select ST_MakePolygon(ST_AddPoint(line, ST_StartPoint(line)))
from (
  select ST_MakeLine(array(
    select ST_MakePoint(
      3650000 + (i % 200) * 120 + 50 * cos(2 * pi() * v / {vertices}),
      4855000 + (i / 200) * 120 + 50 * sin(2 * pi() * v / {vertices}))
    from generate_series(0, {vertices} - 1) as v)) as line
  from generate_series(1, {rows}) as i
) as rings;
create index on {SCHEMA}.{name} using gist (geom);
analyze {SCHEMA}.{name};
""")

    # <b>One table per layer for the composition curve, because a table may
    # appear in a service only once.</b> `layer_table_unique_in_service` is per
    # service, and this half is one service of many layers.
    for i in range(max(LAYERS)):
        sql.append(f"""
drop table if exists {SCHEMA}.wide{i};
create table {SCHEMA}.wide{i} as table {SCHEMA}.r1000_v5;
alter table {SCHEMA}.wide{i} add primary key (objectid);
create index on {SCHEMA}.wide{i} using gist (geom);
analyze {SCHEMA}.wide{i};
""")

    script = "\n".join(sql)

    print(f"generating {len(ROWS) * len(VERTICES) + max(LAYERS)} tables…")

    done = subprocess.run(
        ["docker", "exec", "-i", container, "psql", "-U", "gis", "-d", "gis", "-q"],
        input=script,
        text=True,
        capture_output=True,
        check=False,
    )

    if done.returncode != 0:
        raise SystemExit(done.stderr[-2000:])

    print("generated")


def drop(container):
    subprocess.run(
        ["docker", "exec", "-i", container, "psql", "-U", "gis", "-d", "gis", "-q"],
        input=f"drop schema if exists {SCHEMA} cascade;",
        text=True,
        capture_output=True,
        check=False,
    )

    print("dropped")


class Server:
    """The admin surface, over one session."""

    def __init__(self, url):
        self.url = url.rstrip("/")
        self.opener = urllib.request.build_opener(
            urllib.request.HTTPSHandler(context=ssl._create_unverified_context())
        )
        self.token = None

    def call(self, method, path, body=None, expect=(200, 201)):
        data = json.dumps(body).encode() if body is not None else None
        headers = {"Content-Type": "application/json"} if data else {}

        if self.token:
            headers["Authorization"] = "Bearer " + self.token

        request = urllib.request.Request(
            self.url + path, data=data, headers=headers, method=method
        )

        began = time.perf_counter()

        try:
            with self.opener.open(request, timeout=TIMEOUT) as answer:
                raw = answer.read()
                status = answer.status
                head = dict(answer.headers)
        except urllib.error.HTTPError as refused:
            raw = refused.read()
            status = refused.code
            head = dict(refused.headers)

        took = time.perf_counter() - began

        if expect and status not in expect:
            raise SystemExit(f"{method} {path} answered {status}: {raw[:400]!r}")

        return status, raw, head, took

    def sign_in(self, name, password):
        request = urllib.request.Request(
            self.url + "/rest/auth/login",
            data=json.dumps({"name": name, "password": password}).encode(),
            headers={"Content-Type": "application/json"},
            method="POST",
        )

        with self.opener.open(request, timeout=TIMEOUT) as answer:
            self.token = json.loads(answer.read().decode())["token"]


def layer(name, source, table):
    return {
        "name": name,
        "dataSourceId": source,
        "schemaName": SCHEMA,
        "tableName": table,
        "geometryColumn": "geom",
        "identityColumn": "objectid",
        "srid": 3857,
        "geometryType": "Polygon",
    }


def draw(server, source, tables, repeats):
    """Times one preview of a composition of these tables."""
    body = {
        "name": "preview",
        "nodes": [{"layer": layer(f"L{i}", source, t)} for i, t in enumerate(tables)],
    }

    where = f"?bbox={BBOX}&size={SIZE}&bboxSR=3857"

    # <b>One warm draw thrown away.</b> The first request against a table pays
    # for the shape lookup that `ServiceContexts` then remembers for thirty
    # seconds, and a benchmark that measured it once would report the cache miss
    # as the cost of drawing.
    server.call("POST", "/admin/publish/preview" + where, body)

    times = []
    sampled = None
    ceiling = None

    for _ in range(repeats):
        _, raw, head, took = server.call("POST", "/admin/publish/preview" + where, body)

        times.append(took * 1000)
        sampled = head.get("X-Graticula-Sampled")
        ceiling = head.get("X-Graticula-Ceiling")

    ms = sorted(times)

    return {
        "median_ms": round(statistics.median(ms), 1),
        "min_ms": round(ms[0], 1),
        "max_ms": round(ms[-1], 1),
        "bytes": len(raw),
        "sampled": sampled,
        "ceiling": ceiling,
    }


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--make", action="store_true")
    parser.add_argument("--drop", action="store_true")
    parser.add_argument("--container", default="gis-experiment-postgis")
    parser.add_argument("--url")
    parser.add_argument("--user")
    parser.add_argument("--password")
    parser.add_argument("--source")
    parser.add_argument("--repeats", type=int, default=7)
    parser.add_argument("--out", default="benchmarks/publish-scale/preview.json")

    options = parser.parse_args()

    if options.make:
        corpus(options.container)
        return 0

    if options.drop:
        drop(options.container)
        return 0

    if not (options.url and options.user and options.password and options.source):
        raise SystemExit("--url, --user, --password and --source are required to measure")

    server = Server(options.url)
    server.sign_in(options.user, options.password)

    measured = {
        "url": options.url,
        "at": time.strftime("%Y-%m-%dT%H:%M:%S"),
        "bbox": BBOX,
        "size": SIZE,
        "repeats": options.repeats,
        "rows": {},
        "layers": {},
    }

    for rows in ROWS:
        for vertices in VERTICES:
            key = f"{rows}x{vertices}"
            measured["rows"][key] = draw(
                server, options.source, [f"r{rows}_v{vertices}"], options.repeats
            )

            print(f"{key:>12}: {json.dumps(measured['rows'][key])}")

    for count in LAYERS:
        measured["layers"][str(count)] = draw(
            server,
            options.source,
            [f"wide{i}" for i in range(count)],
            options.repeats,
        )

        print(f"{count:>4} layers: {json.dumps(measured['layers'][str(count)])}")

    with open(options.out, "w", encoding="utf-8") as out:
        json.dump(measured, out, indent=2)
        out.write("\n")

    return 0


if __name__ == "__main__":
    sys.exit(main())
