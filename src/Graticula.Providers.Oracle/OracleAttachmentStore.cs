using System;
using System.Collections.Generic;
using System.Data;
using System.Globalization;
using System.IO;
using System.Text.Json;
using System.Threading;
using System.Threading.Tasks;
using Graticula.Catalog;
using Graticula.Features;
using Oracle.ManagedDataAccess.Client;
using Oracle.ManagedDataAccess.Types;

namespace Graticula.Providers.Oracle;

/// <summary>
/// A registered Oracle layer's attachments kept beside its table — ADR-207 — in <c>&lt;TABLE&gt;__ATTACH</c>, Esri's
/// name and shape for the same thing in an Oracle geodatabase: one row per attachment with its bytes in a BLOB.
/// </summary>
/// <remarks>
/// <para>
/// <b>A BLOB, streamed both ways, rather than PostgreSQL's chunk table.</b> The PostGIS store chunks because a
/// <c>bytea</c> parameter cannot stream; an Oracle LOB can. An upload inserts an empty BLOB and writes the request into
/// its locator a block at a time; a download hands the client the locator itself, which is a stream reading the
/// database a block at a time. Memory is one block either way, which is what ADR-013 §4a asks.
/// </para>
/// <para>
/// <b>The foreign key cascades</b>, as the PostGIS store's does: a feature deleted by any tool takes its attachments.
/// A missing feature is the database's refusal (ORA-02291), said as one.
/// </para>
/// </remarks>
public sealed class OracleAttachmentStore : IAttachmentStore
{
    /// <summary>The suffix Esri gives the table, so one already there is the one used.</summary>
    public const string Suffix = "__ATTACH";

    private const int BlockBytes = 64 * 1024;

    private readonly string _connectionString;
    private readonly LayerDefinition _layer;
    private readonly long _quota;

    /// <summary>Creates the store.</summary>
    /// <param name="locator">The data source's <c>oracle:</c> locator.</param>
    /// <param name="layer">The layer.</param>
    /// <param name="quotaBytes">How much it may store.</param>
    public OracleAttachmentStore(string locator, LayerDefinition layer, long quotaBytes)
    {
        ArgumentException.ThrowIfNullOrEmpty(locator);
        ArgumentNullException.ThrowIfNull(layer);

        _connectionString = OracleConnections.For(locator, pooling: true);
        _layer = layer;
        _quota = quotaBytes;
    }

    /// <summary>The table's name.</summary>
    public string TableName => _layer.TableName + Suffix;

    private string Qualified => $"{LayerDefinition.Quote(_layer.SchemaName)}.{LayerDefinition.Quote(TableName)}";

    private Task<OracleConnection> OpenAsync(CancellationToken cancellationToken) =>
        OracleConnections.OpenAsync(_connectionString, cancellationToken);

    private static OracleCommand Command(string sql, OracleConnection connection) => new(sql, connection) { BindByName = true };

    /// <summary>Creates the table, when it is not there — switching attachments on (ADR-207).</summary>
    /// <param name="cancellationToken">Cancellation.</param>
    /// <returns>A task.</returns>
    /// <exception cref="OracleException">The connected user may not create it; the caller says which right.</exception>
    public async Task EnsureTableAsync(CancellationToken cancellationToken)
    {
        string id = LayerDefinition.Quote(_layer.IntegerIdentityColumn ?? _layer.IdentityColumn);

        await using OracleConnection connection = await OpenAsync(cancellationToken).ConfigureAwait(false);

        foreach (string statement in (string[])
                 [
                     $"""
                      create table if not exists {Qualified} (
                        ATTACHMENTID  number generated by default as identity primary key,
                        REL_OBJECTID  number not null references {_layer.QuotedTable} ({id}) on delete cascade,
                        ATT_NAME      varchar2(250 char) not null,
                        CONTENT_TYPE  varchar2(150 char) not null,
                        DECLARED_TYPE varchar2(150 char),
                        DATA_SIZE     number not null,
                        UPLOADED_AT   timestamp with time zone default systimestamp not null,
                        DATA          blob
                      )
                      """,
                     $"create index if not exists {LayerDefinition.Quote(_layer.SchemaName)}.{LayerDefinition.Quote(TableName + "_REL")} on {Qualified} (REL_OBJECTID)",
                 ])
        {
            await using OracleCommand command = Command(statement, connection);
            await command.ExecuteNonQueryAsync(cancellationToken).ConfigureAwait(false);
        }

        // <b>A table of that name already there may be Esri's</b>, keyed by REL_GLOBALID: `if not exists` would keep it,
        // and the first upload would fail on a column it lacks. Reading one is ADR-013 §4c's migration, not this.
        await using OracleCommand shape = Command(
            "select count(*) from all_tab_columns where owner = :p_owner and table_name = :p_table and column_name in ('REL_OBJECTID', 'DATA_SIZE', 'DATA')",
            connection);
        shape.Parameters.Add("p_owner", _layer.SchemaName);
        shape.Parameters.Add("p_table", TableName);

        if (Convert.ToInt32(await shape.ExecuteScalarAsync(cancellationToken).ConfigureAwait(false), CultureInfo.InvariantCulture) != 3)
        {
            throw new InvalidOperationException(
                $"{_layer.SchemaName}.{TableName} is already there and is not a table this server made — an Esri geodatabase's "
                + "keys its attachments by REL_GLOBALID. Reading one is not built (ADR-013 §4c); keep this layer's attachments in "
                + "the datastore instead, or rename that table.");
        }
    }

    /// <summary>How many attachments there are and how many bytes they hold.</summary>
    /// <param name="cancellationToken">Cancellation.</param>
    /// <returns>The count and the bytes; zero when the table was never made.</returns>
    public async Task<(long Count, long Bytes)> CountAsync(CancellationToken cancellationToken)
    {
        await using OracleConnection connection = await OpenAsync(cancellationToken).ConfigureAwait(false);
        await using OracleCommand command = Command($"select count(*), nvl(sum(DATA_SIZE), 0) from {Qualified}", connection);

        try
        {
            await using OracleDataReader reader = await command.ExecuteReaderAsync(cancellationToken).ConfigureAwait(false);
            await reader.ReadAsync(cancellationToken).ConfigureAwait(false);
            return (Convert.ToInt64(reader.GetValue(0), CultureInfo.InvariantCulture), Convert.ToInt64(reader.GetValue(1), CultureInfo.InvariantCulture));
        }
        catch (OracleException e) when (Missing(e))
        {
            return (0, 0);
        }
    }

    /// <summary>Drops the table and every attachment in it — switching attachments off (ADR-207).</summary>
    /// <param name="cancellationToken">Cancellation.</param>
    /// <returns>A task.</returns>
    public async Task DropAsync(CancellationToken cancellationToken)
    {
        await using OracleConnection connection = await OpenAsync(cancellationToken).ConfigureAwait(false);
        await using OracleCommand command = Command($"drop table if exists {Qualified} purge", connection);
        await command.ExecuteNonQueryAsync(cancellationToken).ConfigureAwait(false);
    }

    /// <inheritdoc/>
    public async Task<IReadOnlyList<AttachmentInfo>> ListAsync(long featureId, CancellationToken cancellationToken)
    {
        await using OracleConnection connection = await OpenAsync(cancellationToken).ConfigureAwait(false);
        await using OracleCommand command = Command(
            $"select {InfoColumns} from {Qualified} where REL_OBJECTID = :p_feature order by ATTACHMENTID", connection);

        command.Parameters.Add("p_feature", OracleDbType.Int64, featureId, ParameterDirection.Input);

        List<AttachmentInfo> found = [];

        try
        {
            await using OracleDataReader reader = await command.ExecuteReaderAsync(cancellationToken).ConfigureAwait(false);

            while (await reader.ReadAsync(cancellationToken).ConfigureAwait(false))
            {
                found.Add(InfoOf(reader));
            }
        }
        catch (OracleException e) when (Missing(e))
        {
            return [];
        }

        return found;
    }

    /// <inheritdoc/>
    public async Task<OpenAttachment?> OpenAsync(int attachmentId, CancellationToken cancellationToken)
    {
        OracleConnection connection = await OpenAsync(cancellationToken).ConfigureAwait(false);
        OracleCommand? command = null;
        OracleDataReader? reader = null;

        try
        {
            command = Command($"select {InfoColumns}, DATA from {Qualified} where ATTACHMENTID = :p_id", connection);
            command.Parameters.Add("p_id", OracleDbType.Int32, attachmentId, ParameterDirection.Input);

            // The BLOB is read through its locator, a block at a time, not fetched whole with the row.
            command.InitialLOBFetchSize = 0;

            reader = await command.ExecuteReaderAsync(cancellationToken).ConfigureAwait(false);

            if (!await reader.ReadAsync(cancellationToken).ConfigureAwait(false))
            {
                await DisposeAllAsync(reader, command, connection).ConfigureAwait(false);
                return null;
            }

            AttachmentInfo info = InfoOf(reader);
            Stream content = reader.IsDBNull(7) ? Stream.Null : reader.GetOracleBlob(7);
            OracleDataReader held = reader;
            OracleCommand heldCommand = command;

            return new OpenAttachment(info, content, async () =>
            {
                await content.DisposeAsync().ConfigureAwait(false);
                await DisposeAllAsync(held, heldCommand, connection).ConfigureAwait(false);
            });
        }
        catch (OracleException e) when (Missing(e))
        {
            await DisposeAllAsync(reader, command, connection).ConfigureAwait(false);
            return null;
        }
        catch
        {
            await DisposeAllAsync(reader, command, connection).ConfigureAwait(false);
            throw;
        }
    }

    /// <inheritdoc/>
    public async Task<int> AddAsync(
        long featureId,
        string name,
        string contentType,
        string? declaredContentType,
        Stream content,
        CancellationToken cancellationToken)
    {
        ArgumentNullException.ThrowIfNull(content);

        await using OracleConnection connection = await OpenAsync(cancellationToken).ConfigureAwait(false);
        using OracleTransaction transaction = connection.BeginTransaction(IsolationLevel.ReadCommitted);

        int id;
        OracleBlob blob;

        await using (OracleCommand insert = Command(
            $"""
             insert into {Qualified} (REL_OBJECTID, ATT_NAME, CONTENT_TYPE, DECLARED_TYPE, DATA_SIZE, DATA)
             values (:p_feature, :p_name, :p_type, :p_declared, 0, empty_blob())
             returning ATTACHMENTID, DATA into :p_id, :p_data
             """, connection))
        {
            insert.Parameters.Add("p_feature", OracleDbType.Int64, featureId, ParameterDirection.Input);
            insert.Parameters.Add("p_name", OracleDbType.Varchar2, name, ParameterDirection.Input);
            insert.Parameters.Add("p_type", OracleDbType.Varchar2, contentType, ParameterDirection.Input);
            insert.Parameters.Add("p_declared", OracleDbType.Varchar2, (object?)declaredContentType ?? DBNull.Value, ParameterDirection.Input);
            OracleParameter made = insert.Parameters.Add("p_id", OracleDbType.Int32, ParameterDirection.Output);
            OracleParameter locator = insert.Parameters.Add("p_data", OracleDbType.Blob, ParameterDirection.Output);

            try
            {
                await insert.ExecuteNonQueryAsync(cancellationToken).ConfigureAwait(false);
            }
            catch (OracleException e) when (OracleDataSourceProbe.NumberOf(e) == 2291)
            {
                transaction.Rollback();
                throw new AttachmentFeatureMissingException($"There is no feature {featureId} in this layer, so nothing was attached.", e);
            }

            id = Convert.ToInt32(made.Value.ToString(), CultureInfo.InvariantCulture);
            blob = (OracleBlob)locator.Value;
        }

        long total = await WriteAsync(blob, content, cancellationToken).ConfigureAwait(false);

        await SizeAndCheckAsync(connection, transaction, id, total, "Nothing was stored.", cancellationToken).ConfigureAwait(false);

        transaction.Commit();
        return id;
    }

    /// <inheritdoc/>
    public async Task<bool> UpdateAsync(
        long featureId,
        int attachmentId,
        string name,
        string contentType,
        string? declaredContentType,
        Stream content,
        CancellationToken cancellationToken)
    {
        ArgumentNullException.ThrowIfNull(content);

        await using OracleConnection connection = await OpenAsync(cancellationToken).ConfigureAwait(false);
        using OracleTransaction transaction = connection.BeginTransaction(IsolationLevel.ReadCommitted);

        OracleBlob blob;

        // The feature is part of the key, for the PostGIS store's reason: an attachment id is a guessable integer.
        await using (OracleCommand claim = Command(
            $"""
             begin
               update {Qualified}
                  set ATT_NAME = :p_name, CONTENT_TYPE = :p_type, DECLARED_TYPE = :p_declared, DATA_SIZE = 0,
                      UPLOADED_AT = systimestamp, DATA = empty_blob()
                where ATTACHMENTID = :p_id and REL_OBJECTID = :p_feature
                returning DATA into :p_data;
               :p_n := sql%rowcount;
             end;
             """, connection))
        {
            claim.Parameters.Add("p_name", OracleDbType.Varchar2, name, ParameterDirection.Input);
            claim.Parameters.Add("p_type", OracleDbType.Varchar2, contentType, ParameterDirection.Input);
            claim.Parameters.Add("p_declared", OracleDbType.Varchar2, (object?)declaredContentType ?? DBNull.Value, ParameterDirection.Input);
            claim.Parameters.Add("p_id", OracleDbType.Int32, attachmentId, ParameterDirection.Input);
            claim.Parameters.Add("p_feature", OracleDbType.Int64, featureId, ParameterDirection.Input);
            OracleParameter locator = claim.Parameters.Add("p_data", OracleDbType.Blob, ParameterDirection.Output);
            OracleParameter changed = claim.Parameters.Add("p_n", OracleDbType.Int32, ParameterDirection.Output);

            try
            {
                await claim.ExecuteNonQueryAsync(cancellationToken).ConfigureAwait(false);
            }
            catch (OracleException e) when (Missing(e))
            {
                transaction.Rollback();
                return false;
            }

            if (Convert.ToInt32(changed.Value.ToString(), CultureInfo.InvariantCulture) == 0)
            {
                transaction.Rollback();
                return false;
            }

            blob = (OracleBlob)locator.Value;
        }

        long total = await WriteAsync(blob, content, cancellationToken).ConfigureAwait(false);

        await SizeAndCheckAsync(connection, transaction, attachmentId, total, "The attachment was left as it was.", cancellationToken)
            .ConfigureAwait(false);

        transaction.Commit();
        return true;
    }

    /// <inheritdoc/>
    public async Task<IReadOnlyList<int>> DeleteAsync(IReadOnlyList<int> attachmentIds, CancellationToken cancellationToken)
    {
        ArgumentNullException.ThrowIfNull(attachmentIds);

        if (attachmentIds.Count == 0)
        {
            return [];
        }

        await using OracleConnection connection = await OpenAsync(cancellationToken).ConfigureAwait(false);
        await using OracleCommand command = Command(
            $"select ATTACHMENTID from {Qualified} where ATTACHMENTID in (select j.v from json_table(:p_ids, '$[*]' columns (v number path '$')) j)",
            connection);
        command.Parameters.Add("p_ids", OracleDbType.Clob, JsonSerializer.Serialize(attachmentIds), ParameterDirection.Input);

        List<int> found = [];

        try
        {
            await using (OracleDataReader reader = await command.ExecuteReaderAsync(cancellationToken).ConfigureAwait(false))
            {
                while (await reader.ReadAsync(cancellationToken).ConfigureAwait(false))
                {
                    found.Add(Convert.ToInt32(reader.GetValue(0), CultureInfo.InvariantCulture));
                }
            }

            if (found.Count > 0)
            {
                await using OracleCommand delete = Command(
                    $"delete from {Qualified} where ATTACHMENTID in (select j.v from json_table(:p_ids, '$[*]' columns (v number path '$')) j)",
                    connection);
                delete.Parameters.Add("p_ids", OracleDbType.Clob, JsonSerializer.Serialize(found), ParameterDirection.Input);
                await delete.ExecuteNonQueryAsync(cancellationToken).ConfigureAwait(false);
            }
        }
        catch (OracleException e) when (Missing(e))
        {
            return [];
        }

        return found;
    }

    /// <inheritdoc/>
    public async Task<AttachmentUsage> UsageAsync(CancellationToken cancellationToken) =>
        new((await CountAsync(cancellationToken).ConfigureAwait(false)).Bytes, _quota);

    private const string InfoColumns = "ATTACHMENTID, REL_OBJECTID, ATT_NAME, CONTENT_TYPE, DECLARED_TYPE, DATA_SIZE, UPLOADED_AT";

    private static AttachmentInfo InfoOf(OracleDataReader reader) => new(
        Convert.ToInt32(reader.GetValue(0), CultureInfo.InvariantCulture),
        Convert.ToInt64(reader.GetValue(1), CultureInfo.InvariantCulture),
        reader.GetString(2),
        reader.GetString(3),
        reader.IsDBNull(4) ? null : reader.GetString(4),
        Convert.ToInt64(reader.GetValue(5), CultureInfo.InvariantCulture),
        reader.GetDateTimeOffset(6));

    /// <summary>ORA-00942: the table was never made, which means no attachments rather than an error.</summary>
    private static bool Missing(OracleException e) => OracleDataSourceProbe.NumberOf(e) == 942;

    /// <summary>Writes the upload into the BLOB a block at a time, through one rented buffer.</summary>
    private static async Task<long> WriteAsync(OracleBlob blob, Stream content, CancellationToken cancellationToken)
    {
        byte[] buffer = System.Buffers.ArrayPool<byte>.Shared.Rent(BlockBytes);
        long total = 0;

        try
        {
            blob.BeginChunkWrite();

            while (true)
            {
                int read = await content.ReadAsync(buffer.AsMemory(0, BlockBytes), cancellationToken).ConfigureAwait(false);

                if (read == 0)
                {
                    break;
                }

                blob.Write(buffer, 0, read);
                total += read;
            }

            blob.EndChunkWrite();
        }
        finally
        {
            System.Buffers.ArrayPool<byte>.Shared.Return(buffer);
        }

        return total;
    }

    /// <summary>
    /// Records the size and checks the quota inside the transaction, after the write — the PostGIS store's order, the
    /// one that is both exact and reversible.
    /// </summary>
    private async Task SizeAndCheckAsync(
        OracleConnection connection, OracleTransaction transaction, int id, long total, string kept, CancellationToken cancellationToken)
    {
        await using (OracleCommand size = Command($"update {Qualified} set DATA_SIZE = :p_size where ATTACHMENTID = :p_id", connection))
        {
            size.Parameters.Add("p_size", OracleDbType.Int64, total, ParameterDirection.Input);
            size.Parameters.Add("p_id", OracleDbType.Int32, id, ParameterDirection.Input);
            await size.ExecuteNonQueryAsync(cancellationToken).ConfigureAwait(false);
        }

        await using OracleCommand sum = Command($"select nvl(sum(DATA_SIZE), 0) from {Qualified}", connection);
        long used = Convert.ToInt64(await sum.ExecuteScalarAsync(cancellationToken).ConfigureAwait(false), CultureInfo.InvariantCulture);

        if (used > _quota)
        {
            transaction.Rollback();

            throw new AttachmentQuotaExceededException(
                $"This layer's attachments would reach {used:N0} bytes against a quota of {_quota:N0}. {kept} "
                + "Delete some attachments or raise the quota.");
        }
    }

    private static async ValueTask DisposeAllAsync(OracleDataReader? reader, OracleCommand? command, OracleConnection connection)
    {
        if (reader is not null)
        {
            await reader.DisposeAsync().ConfigureAwait(false);
        }

        if (command is not null)
        {
            await command.DisposeAsync().ConfigureAwait(false);
        }

        await connection.DisposeAsync().ConfigureAwait(false);
    }
}
