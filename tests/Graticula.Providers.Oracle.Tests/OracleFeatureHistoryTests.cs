using System;
using System.Collections.Generic;
using System.Linq;
using System.Threading;
using System.Threading.Tasks;
using Graticula.Catalog;
using Graticula.Features;
using Graticula.Geometries;
using Oracle.ManagedDataAccess.Client;
using Xunit;

namespace Graticula.Providers.Oracle.Tests;

/// <summary>
/// ADR-207 condition 4: an Oracle layer's history, kept by a trigger beside its table — every version, the editor
/// this server names and the user another tool connects as, a read at a moment, a restore, and switching it off.
/// </summary>
[Trait("Needs", "Oracle")]
public sealed class OracleFeatureHistoryTests
{
    private static readonly CancellationToken None = CancellationToken.None;

    private static string Owner => OracleFixture.Source.User.ToUpperInvariant();

    private static async Task ExecuteAsync(string sql)
    {
        await using OracleConnection connection = await OracleConnections.OpenAsync(
            OracleConnections.For(OracleFixture.Locator, pooling: true), None);
        await using OracleCommand command = new(sql, connection);
        await command.ExecuteNonQueryAsync(None);
    }

    [Fact]
    public async Task A_history_records_every_version_answers_a_moment_and_restores_a_deleted_feature()
    {
        const string Table = "ZZT_HISTORY";

        await ExecuteAsync($"drop table if exists {Table}__HISTORY purge");
        await ExecuteAsync($"delete from user_sdo_geom_metadata where table_name in ('{Table}', '{Table}__HISTORY')");
        await ExecuteAsync($"drop table if exists {Table} purge");
        await ExecuteAsync($"create table {Table} (objectid number(10) generated by default as identity primary key, label varchar2(20), size_m number, shape sdo_geometry)");
        await ExecuteAsync($"insert into user_sdo_geom_metadata values ('{Table}', 'SHAPE', sdo_dim_array(sdo_dim_element('X', -180, 180, 0.05), sdo_dim_element('Y', -90, 90, 0.05)), 4326)");
        await ExecuteAsync($"create index {Table}_SX on {Table} (shape) indextype is mdsys.spatial_index_v2");
        await ExecuteAsync($"insert into {Table} (label, size_m, shape) values ('one', 1.5, sdo_geometry(2001, 4326, sdo_point_type(30, 40, null), null, null))");
        await ExecuteAsync($"insert into {Table} (label, size_m, shape) values ('two', 2.5, sdo_geometry(2001, 4326, sdo_point_type(31, 41, null), null, null))");

        LayerDefinition layer = new(Table, Owner, Table, "SHAPE", 4326, "OBJECTID", "OBJECTID", isHosted: false);
        OracleFeatureHistory history = new(OracleFixture.Locator, layer);
        OracleFeatureSource source = new(OracleFixture.Locator, layer, new FailingProjector());

        Assert.Equal(2, await history.EnableAsync(None));
        Assert.True((await source.DescribeAsync(None)).Archived);

        await Task.Delay(1_100);
        DateTimeOffset before = DateTimeOffset.UtcNow;
        await Task.Delay(1_100);

        LayerDescription described = await source.DescribeAsync(None);
        OracleFeatureWriter writer = new(OracleFixture.Locator, layer, described.Fields, new FailingProjector());

        EditOutcome edited = await writer.ApplyAsync(
            new EditBatch([], [new FeatureUpdate(1, new Dictionary<string, object?> { ["LABEL"] = "changed" }, null)], [2], Editor: "ayse"),
            None);
        Assert.True(edited.AllSucceeded);

        await ExecuteAsync($"update {Table} set label = 'by sql' where objectid = 1");

        IReadOnlyList<FeatureChange> changes = await history.ChangesAsync(null, 10, None);
        Assert.Contains(changes, c => c is { ObjectId: 1, Kind: "updated", Editor: "ayse", Direct: false });
        Assert.Contains(changes, c => c is { ObjectId: 2, Kind: "deleted", Editor: "ayse", Direct: false });
        Assert.Contains(changes, c => c.ObjectId == 1 && c.Kind == "updated" && c.Direct && c.Editor == Owner);

        // The layer as it was: both features, with their labels and sizes then.
        List<Feature> then = [];
        await foreach (Feature f in source.ReadAsync(new FeatureQuery(10, fields: ["LABEL", "SIZE_M"], orderBy: [new SortKey("OBJECTID", false)]) { HistoricMoment = before }, None))
        {
            then.Add(f);
        }

        Assert.Equal(["one", "two"], then.Select(f => (string?)f[0]));
        Assert.Equal([1.5, 2.5], then.Select(f => Convert.ToDouble(f[1], System.Globalization.CultureInfo.InvariantCulture)));
        Assert.All(then, f => Assert.IsAssignableFrom<Point>(f.Geometry));

        FeatureVersion deleted = Assert.Single(await history.VersionsAsync(2, None));
        Assert.Equal("delete", deleted.ClosedBy);

        RestoreOutcome restored = await history.RestoreAsync(2, deleted.HistoryId, "ayse", null, None);
        Assert.Equal(RestoreResult.Recreated, restored.Result);
        Assert.Equal(1, await source.CountAsync(new FeatureQuery(1, identities: [2]), None));
        Assert.Contains(await history.ChangesAsync(null, 10, None), c => c is { ObjectId: 2, Kind: "restored" });

        Assert.True(await history.SetKeepAsync(30, None));
        Assert.Equal(30, (await history.KeptAsync(None))?.KeepDays);

        await history.DisableAsync(None);
        Assert.False(await history.IsOnAsync(None));
        Assert.False((await source.DescribeAsync(None)).Archived);
    }

    private sealed class FailingProjector : IProjector
    {
        public Task<(IReadOnlyList<Geometry> Projected, ProjectionProvenance Provenance)> ProjectAsync(
            IReadOnlyList<Geometry> geometries, int fromSrid, int toSrid, CancellationToken cancellationToken) =>
            throw new InvalidOperationException($"Asked to move EPSG:{fromSrid} to EPSG:{toSrid}.");

        public Task<IReadOnlyList<Geometry>?> ProjectToDefinitionAsync(
            IReadOnlyList<Geometry> geometries, int fromSrid, string definition, CancellationToken cancellationToken) =>
            throw new InvalidOperationException("Asked for a written reference.");

        public Task<IReadOnlyList<Geometry>> GeneralizeAsync(
            IReadOnlyList<Geometry> geometries, int fromSrid, int toSrid, double tolerance, CancellationToken cancellationToken) =>
            throw new InvalidOperationException("Asked to generalize.");

        public Task<bool> KnowsAsync(int srid, CancellationToken cancellationToken) => Task.FromResult(true);

        public Task<Envelope?> DomainOfAsync(int srid, CancellationToken cancellationToken) =>
            Task.FromResult<Envelope?>(null);

        public Task<IReadOnlyList<KnownReference>> ReferencesAsync(CancellationToken cancellationToken) =>
            Task.FromResult<IReadOnlyList<KnownReference>>([]);

        public Task<ProjectionProvenance> DescribeAsync(int fromSrid, int toSrid, CancellationToken cancellationToken) =>
            throw new InvalidOperationException("Asked to describe a projection.");
    }
}
