using System;
using System.Collections.Generic;
using System.Linq;
using System.Threading;
using System.Threading.Tasks;
using Graticula.Catalog;
using Graticula.Features;
using Graticula.Geometries;
using Graticula.Platform.Admin;
using Oracle.ManagedDataAccess.Client;
using Xunit;

namespace Graticula.Providers.Oracle.Tests;

/// <summary>
/// An Oracle table with no SDO_GEOMETRY column, served as a table — ADR-213 condition 7: listed by the probe, described
/// with no extent, read without shapes whatever filter is sent, edited with its attributes alone, and kept without a
/// history.
/// </summary>
[Trait("Needs", "Oracle")]
public sealed class OracleTableTests
{
    private static readonly CancellationToken None = CancellationToken.None;

    private static string Owner => OracleFixture.Source.User.ToUpperInvariant();

    private static LayerDefinition Table(string name) =>
        new(name, Owner, name, null, LayerDefinition.TableSrid, "OBJECTID", "OBJECTID", isHosted: false);

    private static async Task ExecuteAsync(string sql)
    {
        await using OracleConnection connection = await OracleConnections.OpenAsync(
            OracleConnections.For(OracleFixture.Locator, pooling: true), None);
        await using OracleCommand command = new(sql, connection);
        await command.ExecuteNonQueryAsync(None);
    }

    private static async Task<(OracleFeatureSource Source, OracleFeatureWriter Writer)> MadeAsync(string name)
    {
        await ExecuteAsync($"drop table if exists {name} purge");
        await ExecuteAsync(
            $"create table {name} (objectid number(10) generated by default as identity primary key, "
            + "site_code varchar2(10), score number(5))");
        await ExecuteAsync($"insert into {name} (site_code, score) select 'A1', 4 from dual union all "
            + "select 'A1', 2 from dual union all select 'B2', 5 from dual");

        LayerDefinition layer = Table(name);
        OracleFeatureSource source = new(OracleFixture.Locator, layer, new NoProjector());
        LayerDescription described = await source.DescribeAsync(None);

        return (source, new OracleFeatureWriter(OracleFixture.Locator, layer, described.Fields, new NoProjector()));
    }

    [Fact]
    public async Task A_table_is_described_without_an_extent_and_read_without_shapes_whatever_the_filter()
    {
        (OracleFeatureSource source, _) = await MadeAsync("ZZTB_READ");

        LayerDescription described = await source.DescribeAsync(None);

        Assert.Null(described.Extent);
        Assert.Null(described.SpatiallyIndexed);
        Assert.Equal(["OBJECTID", "SITE_CODE", "SCORE"], described.Fields.Select(f => f.Name));

        // A box and a relation are ignored, as ArcGIS ignores them on a table; every row comes back with no shape.
        FeatureQuery asked = new(
            10,
            boundingBox: new Envelope(0, 0, 1, 1),
            fields: ["OBJECTID", "SITE_CODE"],
            includeGeometry: true,
            spatial: new SpatialFilter(new Point(50, 50)))
        {
            ReturnCentroid = true,
        };

        List<Feature> rows = [];

        await foreach (Feature feature in source.ReadAsync(asked, None))
        {
            rows.Add(feature);
        }

        Assert.Equal(3, rows.Count);
        Assert.All(rows, row => Assert.Null(row.Geometry));
        Assert.Equal(3, await source.CountAsync(asked, None));
        Assert.NotNull(await source.VersionOfAsync(1, None));
        Assert.Null(await source.GeometryWidthAsync(None));
        await Assert.ThrowsAsync<QueryNotSupportedException>(() => source.ExtentAsync(new FeatureQuery(10), None));
    }

    [Fact]
    public async Task A_row_is_added_updated_and_deleted_with_its_attributes_and_refused_with_a_shape()
    {
        (OracleFeatureSource source, OracleFeatureWriter writer) = await MadeAsync("ZZTB_EDIT");

        EditOutcome added = await writer.ApplyAsync(
            new EditBatch([new FeatureAdd(new Dictionary<string, object?> { ["SITE_CODE"] = "C3", ["SCORE"] = 1 }, null)], [], []), None);
        EditResult row = Assert.Single(added.Adds);
        Assert.True(row.Succeeded, row.Error);

        EditOutcome changed = await writer.ApplyAsync(
            new EditBatch([], [new FeatureUpdate(row.Identity, new Dictionary<string, object?> { ["SCORE"] = 3 }, null)], []), None);
        EditResult update = Assert.Single(changed.Updates);
        Assert.True(update.Succeeded, update.Error);

        EditOutcome shaped = await writer.ApplyAsync(
            new EditBatch([new FeatureAdd(new Dictionary<string, object?> { ["SITE_CODE"] = "D4" }, new Point(1, 2))], [], []), None);
        EditResult refused = Assert.Single(shaped.Adds);
        Assert.False(refused.Succeeded);
        Assert.Contains("keeps no geometry", refused.Error, StringComparison.Ordinal);

        Assert.Equal(4, await source.CountAsync(new FeatureQuery(10), None));

        EditOutcome deleted = await writer.ApplyAsync(new EditBatch([], [], [row.Identity]), None);
        Assert.True(Assert.Single(deleted.Deletes).Succeeded);
        Assert.Equal(3, await source.CountAsync(new FeatureQuery(10), None));
    }

    [Fact]
    public async Task The_probe_lists_a_table_without_geometry_and_never_this_servers_side_tables()
    {
        await MadeAsync("ZZTB_LISTED");
        await ExecuteAsync("drop table if exists ZZTB_LISTED__ATTACH purge");
        await ExecuteAsync("create table ZZTB_LISTED__ATTACH (attachmentid number(10) primary key, rel_objectid number(10))");

        ProbeResult probed = await new OracleDataSourceProbe().ProbeAsync(OracleFixture.Locator, None);

        SourceTable listed = Assert.Single(probed.Tables, t => t.TableName == "ZZTB_LISTED");
        Assert.Null(listed.GeometryColumn);
        Assert.Equal("OBJECTID", listed.CandidateObjectIdColumn);
        Assert.DoesNotContain(probed.Tables, t => t.TableName == "ZZTB_LISTED__ATTACH");
        Assert.DoesNotContain(probed.Tables, t => t.SchemaName is "SYS" or "SYSTEM" or "MDSYS");
    }

    [Fact]
    public async Task A_history_is_not_kept_for_a_table_and_says_so()
    {
        await MadeAsync("ZZTB_HISTORY");

        InvalidOperationException refused = await Assert.ThrowsAsync<InvalidOperationException>(
            () => new OracleFeatureHistory(OracleFixture.Locator, Table("ZZTB_HISTORY")).EnableAsync(None));

        Assert.Contains("a table has none", refused.Message, StringComparison.Ordinal);
    }

    private sealed class NoProjector : IProjector
    {
        public Task<(IReadOnlyList<Geometry> Projected, ProjectionProvenance Provenance)> ProjectAsync(
            IReadOnlyList<Geometry> geometries, int fromSrid, int toSrid, CancellationToken cancellationToken) =>
            throw new InvalidOperationException("A table has nothing to project.");

        public Task<IReadOnlyList<Geometry>?> ProjectToDefinitionAsync(
            IReadOnlyList<Geometry> geometries, int fromSrid, string definition, CancellationToken cancellationToken) =>
            throw new InvalidOperationException("A table has nothing to project.");

        public Task<IReadOnlyList<Geometry>> GeneralizeAsync(
            IReadOnlyList<Geometry> geometries, int fromSrid, int toSrid, double tolerance, CancellationToken cancellationToken) =>
            throw new InvalidOperationException("A table has nothing to generalize.");

        public Task<bool> KnowsAsync(int srid, CancellationToken cancellationToken) => Task.FromResult(true);

        public Task<Envelope?> DomainOfAsync(int srid, CancellationToken cancellationToken) => Task.FromResult<Envelope?>(null);

        public Task<IReadOnlyList<KnownReference>> ReferencesAsync(CancellationToken cancellationToken) =>
            Task.FromResult<IReadOnlyList<KnownReference>>([]);

        public Task<ProjectionProvenance> DescribeAsync(int fromSrid, int toSrid, CancellationToken cancellationToken) =>
            throw new InvalidOperationException("A table has nothing to project.");
    }
}
