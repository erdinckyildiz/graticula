using System;
using System.Collections.Generic;
using System.Linq;
using System.Threading;
using System.Threading.Tasks;
using Graticula.Catalog;
using Graticula.Features;
using Graticula.Geometries;
using Oracle.ManagedDataAccess.Client;
using Xunit;

namespace Graticula.Providers.Oracle.Tests;

/// <summary>
/// A layer that stores Z, M or both: described, read and written with them. Oracle's own WKB writes an elevation under a
/// geographic reference as 0 and gives a three-ordinate shape a 2D type code, so before SdoShape a 3D line read back with
/// its vertices shifted — these are the tables that showed it.
/// </summary>
[Trait("Needs", "Oracle")]
public sealed class OracleOrdinatesTests
{
    private static readonly CancellationToken None = CancellationToken.None;

    private static string Owner => OracleFixture.Source.User.ToUpperInvariant();

    private static async Task ExecuteAsync(string sql)
    {
        await using OracleConnection connection = await OracleConnections.OpenAsync(
            OracleConnections.For(OracleFixture.Locator, pooling: true), None);
        await using OracleCommand command = new(sql, connection);
        await command.ExecuteNonQueryAsync(None);
    }

    /// <summary>A table whose shape column has the named dimensions, with the rows given.</summary>
    private static async Task<(OracleFeatureSource Source, LayerDefinition Layer)> TableAsync(
        string table, string[] dimensions, params string[] shapes)
    {
        await ExecuteAsync($"drop table if exists {table} purge");
        await ExecuteAsync($"delete from user_sdo_geom_metadata where table_name = '{table}'");
        await ExecuteAsync($"create table {table} (objectid number(10) generated by default as identity primary key, label varchar2(20), shape sdo_geometry)");

        string elements = string.Join(", ", dimensions.Select(d => d switch
        {
            "X" => "sdo_dim_element('X', -180, 180, 0.05)",
            "Y" => "sdo_dim_element('Y', -90, 90, 0.05)",
            _ => $"sdo_dim_element('{d}', -100000, 100000, 0.05)",
        }));

        await ExecuteAsync($"insert into user_sdo_geom_metadata values ('{table}', 'SHAPE', sdo_dim_array({elements}), 4326)");

        foreach (string shape in shapes)
        {
            await ExecuteAsync($"insert into {table} (label, shape) values ('row', {shape})");
        }

        LayerDefinition layer = new(table, Owner, table, "SHAPE", 4326, "OBJECTID", "OBJECTID", isHosted: false);
        return (new OracleFeatureSource(OracleFixture.Locator, layer, new StillProjector()), layer);
    }

    private static async Task<List<Feature>> ReadAsync(OracleFeatureSource source, GeometryOrdinates keep)
    {
        List<Feature> features = [];

        await foreach (Feature feature in source.ReadAsync(new FeatureQuery(100) { KeepOrdinates = keep }, None))
        {
            features.Add(feature);
        }

        return features;
    }

    [Fact]
    public async Task A_three_dimensional_line_is_read_whole_with_and_without_its_elevation()
    {
        (OracleFeatureSource source, _) = await TableAsync(
            "ZZO_LINE_Z", ["X", "Y", "Z"],
            "sdo_geometry(3002, 4326, null, sdo_elem_info_array(1,2,1), sdo_ordinate_array(30, 40, 100, 31, 41, 200))");

        Assert.Equal(GeometryOrdinates.Z, (await source.DescribeAsync(None)).StoredOrdinates);

        LineString flat = Assert.IsType<LineString>(Assert.Single(await ReadAsync(source, GeometryOrdinates.None)).Geometry);
        Assert.Equal([30, 40, 31, 41], flat.Coordinates.ToInterleavedArray());
        Assert.Equal(GeometryOrdinates.None, flat.Coordinates.Ordinates);

        LineString full = Assert.IsType<LineString>(Assert.Single(await ReadAsync(source, GeometryOrdinates.Z)).Geometry);
        Assert.Equal([30, 40, 31, 41], full.Coordinates.ToInterleavedArray());
        Assert.Equal([100.0, 200.0], full.Coordinates.ZSpan().ToArray());
    }

    [Fact]
    public async Task A_point_in_sdo_point_keeps_its_elevation_under_a_geographic_reference()
    {
        (OracleFeatureSource source, _) = await TableAsync(
            "ZZO_POINT_Z", ["X", "Y", "Z"], "sdo_geometry(3001, 4326, sdo_point_type(30, 40, 7), null, null)");

        Point point = Assert.IsAssignableFrom<Point>(Assert.Single(await ReadAsync(source, GeometryOrdinates.Z)).Geometry);
        Assert.Equal(7, point.Z);
    }

    [Fact]
    public async Task A_measured_line_and_a_four_dimensional_one_are_read_with_their_measures()
    {
        (OracleFeatureSource measured, _) = await TableAsync(
            "ZZO_LINE_M", ["X", "Y", "M"],
            "sdo_geometry(3302, 4326, null, sdo_elem_info_array(1,2,1), sdo_ordinate_array(30, 40, 0, 31, 41, 5))");

        Assert.Equal(GeometryOrdinates.M, (await measured.DescribeAsync(None)).StoredOrdinates);
        LineString m = Assert.IsType<LineString>(Assert.Single(await ReadAsync(measured, GeometryOrdinates.M)).Geometry);
        Assert.Equal([0.0, 5.0], m.Coordinates.MSpan().ToArray());

        (OracleFeatureSource both, _) = await TableAsync(
            "ZZO_LINE_ZM", ["X", "Y", "Z", "M"],
            "sdo_geometry(4402, 4326, null, sdo_elem_info_array(1,2,1), sdo_ordinate_array(30, 40, 1, 0, 31, 41, 2, 5))");

        Assert.Equal(GeometryOrdinates.Z | GeometryOrdinates.M, (await both.DescribeAsync(None)).StoredOrdinates);
        LineString zm = Assert.IsType<LineString>(Assert.Single(await ReadAsync(both, GeometryOrdinates.Z | GeometryOrdinates.M)).Geometry);
        Assert.Equal([1.0, 2.0], zm.Coordinates.ZSpan().ToArray());
        Assert.Equal([0.0, 5.0], zm.Coordinates.MSpan().ToArray());

        // Oracle's WKB refuses four ordinates (ORA-13199); without Z and M asked for, the flattened shape is read.
        LineString flat = Assert.IsType<LineString>(Assert.Single(await ReadAsync(both, GeometryOrdinates.None)).Geometry);
        Assert.Equal([30, 40, 31, 41], flat.Coordinates.ToInterleavedArray());
    }

    [Fact]
    public async Task A_box_filter_and_a_count_work_on_a_three_dimensional_layer()
    {
        (OracleFeatureSource source, _) = await TableAsync(
            "ZZO_FILTER_Z", ["X", "Y", "Z"],
            "sdo_geometry(3001, 4326, sdo_point_type(30, 40, 7), null, null)",
            "sdo_geometry(3001, 4326, sdo_point_type(35, 38, 9), null, null)");

        await ExecuteAsync("create index zzo_filter_z_sx on zzo_filter_z (shape) indextype is mdsys.spatial_index_v2 parameters ('sdo_indx_dims=2')");

        Assert.Equal(1, await source.CountAsync(new FeatureQuery(1, boundingBox: new Envelope(29, 39, 31, 41)), None));
        Assert.Equal(1, await source.CountAsync(
            new FeatureQuery(1, spatial: new SpatialFilter(new Polygon(new LinearRing(XySequence.Wrap([34, 37, 36, 37, 36, 39, 34, 39, 34, 37]))))), None));
    }

    [Theory]
    [InlineData("ZZO_WRITE_Z", new[] { "X", "Y", "Z" }, 7.0, null)]
    [InlineData("ZZO_WRITE_M", new[] { "X", "Y", "M" }, null, 9.0)]
    [InlineData("ZZO_WRITE_ZM", new[] { "X", "Y", "Z", "M" }, 7.0, 9.0)]
    public async Task A_shape_with_its_ordinates_is_added_updated_and_read_back(string table, string[] dimensions, double? z, double? m)
    {
        (OracleFeatureSource source, LayerDefinition layer) = await TableAsync(table, dimensions);
        LayerDescription described = await source.DescribeAsync(None);
        OracleFeatureWriter writer = new(OracleFixture.Locator, layer, described.Fields, new StillProjector());
        GeometryOrdinates keep = described.StoredOrdinates;

        LineString sent = new(XySequence.Wrap([30, 40, 31, 41], z is null ? null : [z.Value, z.Value + 1], m is null ? null : [m.Value, m.Value + 1]));
        EditOutcome added = await writer.ApplyAsync(
            new EditBatch([new FeatureAdd(new Dictionary<string, object?> { ["LABEL"] = "w" }, sent)], [], []), None);

        EditResult result = Assert.Single(added.Adds);
        Assert.True(result.Succeeded, result.Error);

        LineString back = Assert.IsType<LineString>(Assert.Single(await ReadAsync(source, keep)).Geometry);
        Assert.Equal(sent.Coordinates, back.Coordinates);

        LineString moved = new(XySequence.Wrap([32, 42, 33, 43], z is null ? null : [z.Value + 5, z.Value + 6], m is null ? null : [m.Value + 5, m.Value + 6]));
        EditOutcome updated = await writer.ApplyAsync(
            new EditBatch([], [new FeatureUpdate(result.Identity, new Dictionary<string, object?>(), moved)], []), None);

        Assert.True(Assert.Single(updated.Updates).Succeeded, updated.Updates[0].Error);
        Assert.Equal(moved.Coordinates, Assert.IsType<LineString>(Assert.Single(await ReadAsync(source, keep)).Geometry).Coordinates);
    }

    [Fact]
    public async Task A_polygon_with_an_elevation_sent_clockwise_is_stored_as_oracle_wants_it()
    {
        (OracleFeatureSource source, LayerDefinition layer) = await TableAsync("ZZO_WRITE_POLY_Z", ["X", "Y", "Z"]);
        LayerDescription described = await source.DescribeAsync(None);
        OracleFeatureWriter writer = new(OracleFixture.Locator, layer, described.Fields, new StillProjector());

        Polygon sent = new(new LinearRing(XySequence.Wrap([30, 40, 30, 41, 31, 41, 31, 40, 30, 40], [1, 2, 3, 4, 1], null)));
        EditOutcome added = await writer.ApplyAsync(new EditBatch([new FeatureAdd(new Dictionary<string, object?>(), sent)], [], []), None);
        Assert.True(Assert.Single(added.Adds).Succeeded, added.Adds[0].Error);

        await using OracleConnection connection = await OracleConnections.OpenAsync(
            OracleConnections.For(OracleFixture.Locator, pooling: true), None);
        await using OracleCommand command = new(
            "select sdo_geom.validate_geometry_with_context(sdo_cs.make_2d(t.shape), 0.05), t.shape.sdo_gtype from zzo_write_poly_z t", connection);
        await using OracleDataReader reader = await command.ExecuteReaderAsync(None);
        Assert.True(await reader.ReadAsync(None));
        Assert.Equal("TRUE", reader.GetString(0));
        Assert.Equal(3003, Convert.ToInt32(reader.GetValue(1)));

        Polygon back = Assert.IsType<Polygon>(Assert.Single(await ReadAsync(source, GeometryOrdinates.Z)).Geometry);
        Assert.Equal(GeometryOrdinates.Z, back.Shell.Coordinates.Ordinates);
        Assert.Equal(5, back.Shell.CoordinateCount);
    }

    /// <summary>A projector for a test that never asks for another reference.</summary>
    private sealed class StillProjector : IProjector
    {
        public Task<(IReadOnlyList<Geometry> Projected, ProjectionProvenance Provenance)> ProjectAsync(
            IReadOnlyList<Geometry> geometries, int fromSrid, int toSrid, CancellationToken cancellationToken) =>
            throw new InvalidOperationException($"Asked to move EPSG:{fromSrid} to EPSG:{toSrid}.");

        public Task<IReadOnlyList<Geometry>?> ProjectToDefinitionAsync(
            IReadOnlyList<Geometry> geometries, int fromSrid, string definition, CancellationToken cancellationToken) =>
            throw new InvalidOperationException("Asked for a written reference.");

        public Task<IReadOnlyList<Geometry>> GeneralizeAsync(
            IReadOnlyList<Geometry> geometries, int fromSrid, int toSrid, double tolerance, CancellationToken cancellationToken) =>
            throw new InvalidOperationException("Asked to generalize.");

        public Task<bool> KnowsAsync(int srid, CancellationToken cancellationToken) => Task.FromResult(true);

        public Task<Envelope?> DomainOfAsync(int srid, CancellationToken cancellationToken) =>
            Task.FromResult<Envelope?>(null);

        public Task<IReadOnlyList<KnownReference>> ReferencesAsync(CancellationToken cancellationToken) =>
            Task.FromResult<IReadOnlyList<KnownReference>>([]);

        public Task<ProjectionProvenance> DescribeAsync(int fromSrid, int toSrid, CancellationToken cancellationToken) =>
            throw new InvalidOperationException("Asked to describe a projection.");
    }
}
