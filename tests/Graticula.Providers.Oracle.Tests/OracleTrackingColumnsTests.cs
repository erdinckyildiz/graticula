using System;
using System.Collections.Generic;
using System.Linq;
using System.Threading;
using System.Threading.Tasks;
using Oracle.ManagedDataAccess.Client;
using Xunit;

namespace Graticula.Providers.Oracle.Tests;

/// <summary>ADR-212: Portal's editor-tracking columns added to a registered Oracle table on an administrator's word, once.</summary>
[Trait("Needs", "Oracle")]
public sealed class OracleTrackingColumnsTests
{
    private static readonly CancellationToken None = CancellationToken.None;

    private static string Owner => OracleFixture.Source.User.ToUpperInvariant();

    private static readonly (string Name, bool Moment)[] Portal =
        [("created_user", false), ("created_date", true), ("last_edited_user", false), ("last_edited_date", true)];

    private static async Task ExecuteAsync(string sql)
    {
        await using OracleConnection connection = await OracleConnections.OpenAsync(OracleConnections.For(OracleFixture.Locator, pooling: true), None);
        await using OracleCommand command = new(sql, connection);
        await command.ExecuteNonQueryAsync(None);
    }

    [Fact]
    public async Task The_four_columns_are_added_once_with_a_name_and_a_moment_type()
    {
        await ExecuteAsync("drop table if exists ZZT_TRACKED purge");
        await ExecuteAsync("create table ZZT_TRACKED (OBJECTID number(10) generated by default as identity primary key, LABEL varchar2(20), SHAPE sdo_geometry)");

        IReadOnlyList<string> added = await OracleTableChecks.AddColumnsAsync(OracleFixture.Locator, Owner, "ZZT_TRACKED", Portal, None);
        Assert.Equal(Portal.Select(p => p.Name), added);
        Assert.Empty(await OracleTableChecks.AddColumnsAsync(OracleFixture.Locator, Owner, "ZZT_TRACKED", Portal, None));

        await using OracleConnection connection = await OracleConnections.OpenAsync(OracleConnections.For(OracleFixture.Locator, pooling: true), None);
        await using OracleCommand types = new(
            "select column_name || ' ' || data_type from user_tab_columns where table_name = 'ZZT_TRACKED' and column_name like '%_%_%' order by column_id",
            connection);
        List<string> found = [];

        await using (OracleDataReader reader = await types.ExecuteReaderAsync(None))
        {
            while (await reader.ReadAsync(None))
            {
                found.Add(reader.GetString(0));
            }
        }

        Assert.Contains("created_user VARCHAR2", found);
        Assert.Contains(found, f => f.StartsWith("created_date TIMESTAMP", StringComparison.Ordinal));
    }
}
