using System;
using System.Collections.Generic;
using System.Linq;
using System.Threading;
using System.Threading.Tasks;
using Graticula.Catalog;
using Graticula.Features;
using Graticula.Geometries;
using Oracle.ManagedDataAccess.Client;
using Xunit;

namespace Graticula.Providers.Oracle.Tests;

/// <summary>
/// A GLOBALID column kept the three ways an Oracle table keeps one — CHAR(38) as an Esri geodatabase does, CHAR(36),
/// RAW(16) as SYS_GUID() makes one — is the layer's GlobalID: typed, minted on add, answered by every edit, filtered on
/// as ArcGIS writes it, and looked up for useGlobalIds.
/// </summary>
[Trait("Needs", "Oracle")]
public sealed class OracleGlobalIdTests
{
    private static readonly CancellationToken None = CancellationToken.None;

    private static string Owner => OracleFixture.Source.User.ToUpperInvariant();

    private static async Task ExecuteAsync(string sql)
    {
        await using OracleConnection connection = await OracleConnections.OpenAsync(
            OracleConnections.For(OracleFixture.Locator, pooling: true), None);
        await using OracleCommand command = new(sql, connection);
        await command.ExecuteNonQueryAsync(None);
    }

    private static async Task<(OracleFeatureSource Source, OracleFeatureWriter Writer, LayerDefinition Layer)> TableAsync(
        string table, string globalId)
    {
        await ExecuteAsync($"drop table if exists {table} purge");
        await ExecuteAsync($"delete from user_sdo_geom_metadata where table_name = '{table}'");
        await ExecuteAsync(
            $"create table {table} (objectid number(10) generated by default as identity primary key, label varchar2(20), "
            + $"globalid {globalId}, shape sdo_geometry)");
        await ExecuteAsync(
            $"insert into user_sdo_geom_metadata values ('{table}', 'SHAPE', sdo_dim_array(sdo_dim_element('X', -180, 180, 0.05), sdo_dim_element('Y', -90, 90, 0.05)), 4326)");

        LayerDefinition layer = new(table, Owner, table, "SHAPE", 4326, "OBJECTID", "OBJECTID", isHosted: false);
        OracleFeatureSource source = new(OracleFixture.Locator, layer, new FailingProjector());
        LayerDescription described = await source.DescribeAsync(None);

        return (source, new OracleFeatureWriter(OracleFixture.Locator, layer, described.Fields, new FailingProjector()), layer);
    }

    [Theory]
    [InlineData("ZZG_BRACED", "char(38)")]
    [InlineData("ZZG_BARE", "varchar2(36)")]
    [InlineData("ZZG_RAW", "raw(16)")]
    public async Task A_globalid_column_is_minted_answered_filtered_and_looked_up(string table, string kept)
    {
        (OracleFeatureSource source, OracleFeatureWriter writer, LayerDefinition layer) = await TableAsync(table, kept);

        LayerDescription described = await source.DescribeAsync(None);
        Assert.Equal("GLOBALID", GlobalIds.FieldOf(described.Fields));

        EditOutcome added = await writer.ApplyAsync(
            new EditBatch([new FeatureAdd(new Dictionary<string, object?> { ["LABEL"] = "a" }, new Point(30, 40))], [], []), None);

        EditResult add = Assert.Single(added.Adds);
        Assert.True(add.Succeeded, add.Error);
        Guid minted = Assert.NotNull(add.GlobalId);

        // Read back as the GUID it was given.
        Feature read = Assert.Single(await ReadAsync(source, new FeatureQuery(10, fields: ["GLOBALID"])));
        Assert.Equal(minted, Assert.IsType<Guid>(read[0]));

        // Filtered on as ArcGIS writes it, and as WFS does — bare and lower-case.
        foreach (string written in new[] { GlobalIds.Braced(minted), minted.ToString("D") })
        {
            Assert.True(WhereClause.TryParse(
                $"GLOBALID = '{written}'", ["OBJECTID", "LABEL", "GLOBALID"], LayerDefinition.Quote, out ParsedWhere where, out string? error,
                new Dictionary<string, FieldType>(StringComparer.OrdinalIgnoreCase)
                {
                    ["OBJECTID"] = FieldType.Integer, ["LABEL"] = FieldType.Text, ["GLOBALID"] = FieldType.Guid,
                }), error);

            Assert.Equal(1, await source.CountAsync(new FeatureQuery(1, where: where), None));
        }

        // useGlobalIds: the object id of a GlobalID.
        IReadOnlyDictionary<Guid, long> ids = await OracleFeatureWriter.ObjectIdsOfAsync(
            OracleFixture.Locator, layer, "GLOBALID", [minted, Guid.NewGuid()], None);
        Assert.Equal(add.Identity, Assert.Single(ids).Value);

        // An update and a delete answer with it too.
        EditOutcome updated = await writer.ApplyAsync(
            new EditBatch([], [new FeatureUpdate(add.Identity, new Dictionary<string, object?> { ["LABEL"] = "b" }, null)], []), None);
        Assert.Equal(minted, Assert.Single(updated.Updates).GlobalId);

        EditOutcome deleted = await writer.ApplyAsync(new EditBatch([], [], [add.Identity]), None);
        Assert.Equal(minted, Assert.Single(deleted.Deletes).GlobalId);
    }

    [Fact]
    public async Task A_globalid_the_client_minted_is_kept_under_use_global_ids()
    {
        (_, OracleFeatureWriter writer, _) = await TableAsync("ZZG_KEPT", "char(38)");
        Guid theirs = Guid.NewGuid();

        EditOutcome added = await writer.ApplyAsync(
            new EditBatch(
                [new FeatureAdd(new Dictionary<string, object?> { ["GLOBALID"] = theirs }, new Point(30, 40))], [], [],
                KeepsGlobalIds: true),
            None);

        Assert.Equal(theirs, Assert.Single(added.Adds).GlobalId);
    }

    private static async Task<List<Feature>> ReadAsync(OracleFeatureSource source, FeatureQuery query)
    {
        List<Feature> features = [];

        await foreach (Feature feature in source.ReadAsync(query, None))
        {
            features.Add(feature);
        }

        return features;
    }

    private sealed class FailingProjector : IProjector
    {
        public Task<(IReadOnlyList<Geometry> Projected, ProjectionProvenance Provenance)> ProjectAsync(
            IReadOnlyList<Geometry> geometries, int fromSrid, int toSrid, CancellationToken cancellationToken) =>
            throw new InvalidOperationException($"Asked to move EPSG:{fromSrid} to EPSG:{toSrid}.");

        public Task<IReadOnlyList<Geometry>?> ProjectToDefinitionAsync(
            IReadOnlyList<Geometry> geometries, int fromSrid, string definition, CancellationToken cancellationToken) =>
            throw new InvalidOperationException("Asked for a written reference.");

        public Task<IReadOnlyList<Geometry>> GeneralizeAsync(
            IReadOnlyList<Geometry> geometries, int fromSrid, int toSrid, double tolerance, CancellationToken cancellationToken) =>
            throw new InvalidOperationException("Asked to generalize.");

        public Task<bool> KnowsAsync(int srid, CancellationToken cancellationToken) => Task.FromResult(true);

        public Task<Envelope?> DomainOfAsync(int srid, CancellationToken cancellationToken) =>
            Task.FromResult<Envelope?>(null);

        public Task<IReadOnlyList<KnownReference>> ReferencesAsync(CancellationToken cancellationToken) =>
            Task.FromResult<IReadOnlyList<KnownReference>>([]);

        public Task<ProjectionProvenance> DescribeAsync(int fromSrid, int toSrid, CancellationToken cancellationToken) =>
            throw new InvalidOperationException("Asked to describe a projection.");
    }
}
